INSERT INTO dm.DimTiempo (
    sk_tiempo, fecha, anio, trimestre, mes, nombre_mes,
    dia, dia_semana, nombre_dia, semana_anio,
    semestre_academico, etiqueta_fecha, es_no_aplica
)
SELECT
    CAST(to_char(f, 'YYYYMMDD') AS INT) AS sk_tiempo,
    f AS fecha,
    EXTRACT(YEAR FROM f) AS anio,
    EXTRACT(QUARTER FROM f) AS trimestre,
    EXTRACT(MONTH FROM f) AS mes,
    CASE EXTRACT(MONTH FROM f)
        WHEN 1 THEN 'Enero'      WHEN 2 THEN 'Febrero'   WHEN 3 THEN 'Marzo'
        WHEN 4 THEN 'Abril'      WHEN 5 THEN 'Mayo'      WHEN 6 THEN 'Junio'
        WHEN 7 THEN 'Julio'      WHEN 8 THEN 'Agosto'    WHEN 9 THEN 'Septiembre'
        WHEN 10 THEN 'Octubre'   WHEN 11 THEN 'Noviembre' ELSE 'Diciembre'
    END AS nombre_mes,
    EXTRACT(DAY FROM f) AS dia,
    EXTRACT(DOW FROM f) AS dia_semana,
    to_char(f, 'Day') AS nombre_dia,
    EXTRACT(WEEK FROM f) AS semana_anio,
    CASE
        WHEN f >= '2026-07-01' AND f <= '2027-01-31' THEN '2026-II'
        WHEN f < '2026-07-01' THEN '2026-I'
        ELSE '2027-I'
    END AS semestre_academico,
    to_char(f, 'YYYY-MM-DD') AS etiqueta_fecha,
    0 AS es_no_aplica
  FROM generate_series(DATE '2020-01-01',DATE '2040-12-31',INTERVAL '1 day') AS fechas(f)
;

