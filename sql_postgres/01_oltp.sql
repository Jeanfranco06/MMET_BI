);

CREATE TABLE dbo.usuarios_sistema (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_estudiante BIGINT NULL,
    nombre_usuario VARCHAR(100) NOT NULL,
    hash_credencial BYTEA NOT NULL,
