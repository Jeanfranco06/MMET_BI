    CONSTRAINT chk_usuario_rol CHECK(rol IN('ESTUDIANTE','COORDINACION','EVALUACION','DIRECCION','ADMIN'))
);

CREATE TABLE dbo.sesiones_autenticacion (
    id_sesion UUID NOT NULL PRIMARY KEY,
