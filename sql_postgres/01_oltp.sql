BEGIN;
-- PostgreSQL 17. Ejecutar en mmet_bi_oltp; no elimina datos.
CREATE SCHEMA IF NOT EXISTS dbo;
CREATE TABLE dbo.cat_practicas (
    id_practica         SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    codigo_practica     VARCHAR(20)   NOT NULL,
    nombre_practica     VARCHAR(100)  NOT NULL,
    descripcion         VARCHAR(200)  NOT NULL,
    es_mixto            SMALLINT            NOT NULL CONSTRAINT df_pract_mixto DEFAULT (0),
    activo              SMALLINT            NOT NULL CONSTRAINT df_pract_activo DEFAULT (1),

    CONSTRAINT uq_cat_practicas_codigo UNIQUE (codigo_practica)
);

CREATE TABLE dbo.cat_instrumentos (
    id_instrumento          SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    codigo_instrumento      VARCHAR(15)   NOT NULL,
    version_instrumento     VARCHAR(30)   NOT NULL,
    nombre_instrumento      VARCHAR(120)  NOT NULL,
    puntaje_minimo          SMALLINT       NOT NULL,
    puntaje_maximo          SMALLINT       NOT NULL,
    requiere_evento_indice  SMALLINT            NOT NULL,
    activo                  SMALLINT            NOT NULL CONSTRAINT df_instr_activo DEFAULT (1),

    CONSTRAINT uq_cat_instr_codigo_ver UNIQUE (codigo_instrumento, version_instrumento),
    CONSTRAINT uq_cat_instr_id_codigo UNIQUE (id_instrumento, codigo_instrumento),
    CONSTRAINT chk_cat_instr_codigo CHECK (codigo_instrumento IN ('PSS-10', 'PCL-5')),
    CONSTRAINT chk_cat_instr_rango CHECK (
        (codigo_instrumento = 'PSS-10' AND puntaje_minimo = 0 AND puntaje_maximo = 40 AND requiere_evento_indice = 0)
        OR
        (codigo_instrumento = 'PCL-5'  AND puntaje_minimo = 0 AND puntaje_maximo = 80 AND requiere_evento_indice = 1)
    )
);

CREATE TABLE dbo.cat_categorias_evento_indice (
    id_categoria_evento SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    codigo_categoria    VARCHAR(40)   NOT NULL,
    nombre_categoria    VARCHAR(120)  NOT NULL,
    activo              SMALLINT            NOT NULL CONSTRAINT df_catevt_activo DEFAULT (1),

    CONSTRAINT uq_cat_evento_codigo UNIQUE (codigo_categoria)
);

CREATE TABLE dbo.estudiantes (
    id_estudiante        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    codigo_estudiante    VARCHAR(50)   NOT NULL,
    nombres              VARCHAR(100)  NOT NULL,
    apellidos            VARCHAR(100)  NOT NULL,
    correo_institucional VARCHAR(150)  NOT NULL,
    edad_anios           SMALLINT       NOT NULL,
    sexo_codificado      VARCHAR(20)   NOT NULL,
    facultad_o_area      VARCHAR(80)   NOT NULL,
    carrera              VARCHAR(120)  NOT NULL,
    ciclo_academico      SMALLINT       NOT NULL,
    creado_en            TIMESTAMPTZ NOT NULL CONSTRAINT df_est_creado DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT uq_est_codigo UNIQUE (codigo_estudiante),
    CONSTRAINT uq_est_correo UNIQUE (correo_institucional),
    CONSTRAINT chk_est_edad_adulto CHECK (edad_anios BETWEEN 18 AND 99),
    CONSTRAINT chk_est_ciclo CHECK (ciclo_academico BETWEEN 1 AND 14)
);

CREATE TABLE dbo.programas (
    id_programa             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    codigo_programa         VARCHAR(40)   NOT NULL,
    nombre_programa         VARCHAR(150)  NOT NULL,
    periodo_academico       VARCHAR(20)   NOT NULL,
    id_practica_principal   SMALLINT       NOT NULL,
    fecha_inicio            DATE           NOT NULL,
    fecha_cierre            DATE           NOT NULL,
    dias_ventana_inicial    SMALLINT       NOT NULL CONSTRAINT df_prog_dvi DEFAULT (14),
    dias_ventana_final      SMALLINT       NOT NULL CONSTRAINT df_prog_dvf DEFAULT (14),
    ventana_inicial_inicio  DATE           NOT NULL,
    ventana_inicial_fin     DATE           NOT NULL,
    ventana_final_inicio    DATE           NOT NULL,
    ventana_final_fin       DATE           NOT NULL,
    estado_programa         VARCHAR(20)   NOT NULL CONSTRAINT df_prog_estado DEFAULT ('PLANIFICADO'),
    creado_en               TIMESTAMPTZ NOT NULL CONSTRAINT df_prog_creado DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT fk_prog_practica
        FOREIGN KEY (id_practica_principal)
        REFERENCES dbo.cat_practicas (id_practica) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_prog_codigo UNIQUE (codigo_programa),
    CONSTRAINT chk_prog_fechas CHECK (fecha_cierre >= fecha_inicio),
    CONSTRAINT chk_prog_dias_ventana CHECK (dias_ventana_inicial >= 0 AND dias_ventana_final >= 0),
    CONSTRAINT chk_prog_ventanas CHECK (
        ventana_inicial_inicio <= ventana_inicial_fin
        AND ventana_final_inicio <= ventana_final_fin
        AND ventana_final_inicio >= ventana_inicial_fin
    ),
    CONSTRAINT chk_prog_estado CHECK (
        estado_programa IN ('PLANIFICADO', 'ACTIVO', 'FINALIZADO', 'CANCELADO')
    )
);

CREATE TABLE dbo.sesiones (
    id_sesion               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_programa             BIGINT         NOT NULL,
    numero_sesion           SMALLINT       NOT NULL,
    id_practica_tecnica     SMALLINT       NOT NULL,
    modalidad               VARCHAR(15)   NOT NULL,
    duracion_programada_min SMALLINT       NOT NULL,
    fecha_sesion            DATE           NOT NULL,
    fecha_hora_inicio       TIMESTAMPTZ NOT NULL,
    estado_sesion           VARCHAR(20)   NOT NULL CONSTRAINT df_ses_estado DEFAULT ('PROGRAMADA'),
    fecha_cambio_estado     TIMESTAMPTZ NOT NULL CONSTRAINT df_ses_fcambio DEFAULT (CURRENT_TIMESTAMP),
    motivo_estado_codigo    VARCHAR(40)   NULL,

    CONSTRAINT fk_ses_programa
        FOREIGN KEY (id_programa)
        REFERENCES dbo.programas (id_programa) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_ses_practica
        FOREIGN KEY (id_practica_tecnica)
        REFERENCES dbo.cat_practicas (id_practica) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_ses_prog_numero UNIQUE (id_programa, numero_sesion),
    CONSTRAINT uq_ses_prog_id UNIQUE (id_programa, id_sesion),
    CONSTRAINT chk_ses_numero CHECK (numero_sesion > 0),
    CONSTRAINT chk_ses_modalidad CHECK (modalidad IN ('PRESENCIAL', 'VIRTUAL', 'HIBRIDA')),
    CONSTRAINT chk_ses_duracion CHECK (duracion_programada_min BETWEEN 5 AND 480),
    CONSTRAINT chk_ses_estado CHECK (
        estado_sesion IN ('PROGRAMADA', 'REALIZADA', 'CANCELADA', 'NO_REALIZADA')
    )
);

CREATE TABLE dbo.asignaciones (
    id_asignacion         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_estudiante         BIGINT         NOT NULL,
    id_programa           BIGINT         NOT NULL,
    fecha_inscripcion     DATE           NOT NULL,
    estado_asignacion     VARCHAR(20)   NOT NULL CONSTRAINT df_asig_estado DEFAULT ('INSCRITO'),
    fecha_retiro          DATE           NULL,
    motivo_retiro_codigo  VARCHAR(40)   NULL,
    actualizado_en        TIMESTAMPTZ NOT NULL CONSTRAINT df_asig_act DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT fk_asig_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES dbo.estudiantes (id_estudiante) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_asig_programa
        FOREIGN KEY (id_programa)
        REFERENCES dbo.programas (id_programa) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_asig_est_prog UNIQUE (id_estudiante, id_programa),
    CONSTRAINT uq_asig_prog_id UNIQUE (id_programa, id_asignacion),
    CONSTRAINT uq_asig_est_prog_id UNIQUE (id_estudiante, id_programa, id_asignacion),
    CONSTRAINT chk_asig_estado CHECK (
        estado_asignacion IN ('INSCRITO', 'ACTIVO', 'RETIRADO', 'COMPLETADO')
    ),
    CONSTRAINT chk_asig_retiro_coherente CHECK (
        (estado_asignacion = 'RETIRADO' AND fecha_retiro IS NOT NULL AND fecha_retiro >= fecha_inscripcion)
        OR
        (estado_asignacion <> 'RETIRADO' AND fecha_retiro IS NULL)
    )
);

CREATE TABLE dbo.asistencias (
    id_asistencia       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_programa         BIGINT         NOT NULL,
    id_asignacion       BIGINT         NOT NULL,
    id_sesion           BIGINT         NOT NULL,
    estado_asistencia   VARCHAR(20)   NOT NULL,
    minutos_asistidos   SMALLINT       NULL,
    registrado_en       TIMESTAMPTZ NOT NULL CONSTRAINT df_asis_reg DEFAULT (CURRENT_TIMESTAMP),
    actualizado_en      TIMESTAMPTZ NOT NULL CONSTRAINT df_asis_act DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT fk_asis_asignacion
        FOREIGN KEY (id_programa, id_asignacion)
        REFERENCES dbo.asignaciones (id_programa, id_asignacion) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_asis_sesion
        FOREIGN KEY (id_programa, id_sesion)
        REFERENCES dbo.sesiones (id_programa, id_sesion) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_asis_asig_sesion UNIQUE (id_asignacion, id_sesion),
    CONSTRAINT chk_asis_estado CHECK (
        estado_asistencia IN ('ASISTIO', 'INASISTENCIA', 'RETIRO_BAJA')
    ),
    CONSTRAINT chk_asis_minutos CHECK (
        minutos_asistidos IS NULL
        OR (estado_asistencia = 'ASISTIO' AND minutos_asistidos > 0 AND minutos_asistidos <= 480)
        OR (estado_asistencia <> 'ASISTIO' AND minutos_asistidos = 0)
    )
);

CREATE TABLE dbo.eventos_indice (
    id_evento_indice            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_estudiante               BIGINT         NOT NULL,
    id_categoria_evento         SMALLINT       NOT NULL,
    codigo_evento_local         VARCHAR(30)   NOT NULL,
    anio_ocurrencia_aprox       SMALLINT       NULL,
    descripcion_evento          VARCHAR(500)  NULL, -- Uso interno OLTP (excluido del Data Mart)
    antecedente_clinico_externo SMALLINT            NOT NULL CONSTRAINT df_evt_ant_ext DEFAULT (0),
    requiere_derivacion         SMALLINT            NOT NULL CONSTRAINT df_evt_deriv   DEFAULT (0),
    vigente                     SMALLINT            NOT NULL CONSTRAINT df_evt_vig DEFAULT (1),
    creado_en                   TIMESTAMPTZ NOT NULL CONSTRAINT df_evt_creado DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT fk_evt_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES dbo.estudiantes (id_estudiante) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_evt_categoria
        FOREIGN KEY (id_categoria_evento)
        REFERENCES dbo.cat_categorias_evento_indice (id_categoria_evento) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_evt_est_codigo UNIQUE (id_estudiante, codigo_evento_local),
    CONSTRAINT uq_evt_est_id UNIQUE (id_estudiante, id_evento_indice),
    CONSTRAINT chk_evt_anio CHECK (
        anio_ocurrencia_aprox IS NULL OR (anio_ocurrencia_aprox BETWEEN 1950 AND 2030)
    )
);

CREATE TABLE dbo.oportunidades_evaluacion (
    id_oportunidad       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_asignacion        BIGINT         NOT NULL,
    id_estudiante        BIGINT         NOT NULL,
    id_programa          BIGINT         NOT NULL,
    id_instrumento       SMALLINT       NOT NULL,
    codigo_instrumento   VARCHAR(15)   NOT NULL,
    id_evento_indice     BIGINT         NULL,
    momento              VARCHAR(10)   NOT NULL,
    fecha_ventana_inicio DATE           NOT NULL,
    fecha_ventana_fin    DATE           NOT NULL,
    fecha_prevista       DATE           NOT NULL,
    aplicable            SMALLINT            NOT NULL CONSTRAINT df_op_apl DEFAULT (1),
    motivo_no_aplicable  VARCHAR(60)   NULL,
    creado_en            TIMESTAMPTZ NOT NULL CONSTRAINT df_op_creado DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT fk_op_asignacion
        FOREIGN KEY (id_estudiante, id_programa, id_asignacion)
        REFERENCES dbo.asignaciones (id_estudiante, id_programa, id_asignacion) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_op_instrumento
        FOREIGN KEY (id_instrumento, codigo_instrumento)
        REFERENCES dbo.cat_instrumentos (id_instrumento, codigo_instrumento) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_op_evento_indice
        FOREIGN KEY (id_estudiante, id_evento_indice)
        REFERENCES dbo.eventos_indice (id_estudiante, id_evento_indice) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_op_id_instr UNIQUE (id_oportunidad, codigo_instrumento),
    CONSTRAINT chk_op_momento CHECK (momento IN ('INICIAL', 'FINAL')),
    CONSTRAINT chk_op_fechas CHECK (
        fecha_ventana_inicio <= fecha_ventana_fin
        AND fecha_prevista BETWEEN fecha_ventana_inicio AND fecha_ventana_fin
    ),
    CONSTRAINT chk_op_aplicabilidad CHECK (
        (aplicable = 1 AND motivo_no_aplicable IS NULL)
        OR
        (aplicable = 0 AND motivo_no_aplicable IS NOT NULL)
    ),
    CONSTRAINT chk_op_evento_segun_instrumento CHECK (
        (codigo_instrumento = 'PSS-10' AND id_evento_indice IS NULL)
        OR
        (codigo_instrumento = 'PCL-5'  AND (aplicable = 0 OR id_evento_indice IS NOT NULL))
    )
);

CREATE TABLE dbo.resultados_evaluacion (
    id_resultado             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_oportunidad           BIGINT         NOT NULL,
    codigo_instrumento       VARCHAR(15)   NOT NULL,
    numero_version           SMALLINT       NOT NULL CONSTRAINT df_res_ver DEFAULT (1),
    puntaje_total            SMALLINT       NOT NULL,
    fecha_realizacion        DATE           NOT NULL,
    en_ventana               SMALLINT            NOT NULL,
    estado_validez           VARCHAR(15)   NOT NULL CONSTRAINT df_res_est DEFAULT ('VALIDO'),
    es_vigente               SMALLINT            NOT NULL CONSTRAINT df_res_vig DEFAULT (1),
    id_resultado_reemplazado BIGINT         NULL,
    motivo_correccion        VARCHAR(150)  NULL,
    vigente_desde            TIMESTAMPTZ NOT NULL CONSTRAINT df_res_vdesde DEFAULT (CURRENT_TIMESTAMP),
    vigente_hasta            TIMESTAMPTZ NULL,

    CONSTRAINT fk_res_oportunidad
        FOREIGN KEY (id_oportunidad, codigo_instrumento)
        REFERENCES dbo.oportunidades_evaluacion (id_oportunidad, codigo_instrumento) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_res_reemplazado
        FOREIGN KEY (id_resultado_reemplazado)
        REFERENCES dbo.resultados_evaluacion (id_resultado) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_res_op_version UNIQUE (id_oportunidad, numero_version),
    CONSTRAINT chk_res_version CHECK (numero_version >= 1),
    CONSTRAINT chk_res_puntaje_rango CHECK (
        (codigo_instrumento = 'PSS-10' AND puntaje_total BETWEEN 0 AND 40)
        OR
        (codigo_instrumento = 'PCL-5'  AND puntaje_total BETWEEN 0 AND 80)
    ),
    CONSTRAINT chk_res_estado CHECK (estado_validez IN ('VALIDO', 'REEMPLAZADO', 'ANULADO')),
    CONSTRAINT chk_res_vigencia_coherente CHECK (
        (es_vigente = 1 AND estado_validez = 'VALIDO' AND vigente_hasta IS NULL)
        OR
        (es_vigente = 0 AND estado_validez IN ('REEMPLAZADO', 'ANULADO') AND vigente_hasta IS NOT NULL)
    ),
    CONSTRAINT chk_res_correccion CHECK (
        (numero_version = 1 AND id_resultado_reemplazado IS NULL)
        OR
        (numero_version > 1 AND id_resultado_reemplazado IS NOT NULL AND motivo_correccion IS NOT NULL)
    ),
    CONSTRAINT chk_res_fechas_vigencia CHECK (
        vigente_hasta IS NULL OR vigente_hasta >= vigente_desde
    )
);

CREATE TABLE dbo.instrumento_versiones (
    id_version_instrumento BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_instrumento SMALLINT NOT NULL,
    numero_version VARCHAR(30) NOT NULL,
    idioma VARCHAR(10) NOT NULL,
    periodo_referencia VARCHAR(80) NOT NULL,
    instrucciones TEXT NULL,
    texto_periodo VARCHAR(500) NULL,
    fuente VARCHAR(500) NOT NULL,
    estado_contenido VARCHAR(20) NOT NULL,
    condiciones_uso VARCHAR(500) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL CONSTRAINT df_instver_creado DEFAULT(CURRENT_TIMESTAMP),
    CONSTRAINT fk_instver_instrumento FOREIGN KEY (id_instrumento) REFERENCES dbo.cat_instrumentos(id_instrumento) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_instver UNIQUE(id_instrumento, numero_version, idioma),
    CONSTRAINT uq_instver_id_instr UNIQUE(id_version_instrumento, id_instrumento),
    CONSTRAINT chk_instver_estado CHECK (estado_contenido IN ('BORRADOR','PUBLICADO','BLOQUEADO'))
);

CREATE TABLE dbo.instrumento_items (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    id_version_instrumento BIGINT NOT NULL,
    numero_item SMALLINT NOT NULL,
    texto_item VARCHAR(2000) NULL,
    puntuacion_inversa SMALLINT NOT NULL CONSTRAINT df_item_inversa DEFAULT(0),
    obligatorio SMALLINT NOT NULL CONSTRAINT df_item_obligatorio DEFAULT(1),
    CONSTRAINT fk_item_version FOREIGN KEY (id_version_instrumento) REFERENCES dbo.instrumento_versiones(id_version_instrumento) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT uq_item_num UNIQUE(id_version_instrumento, numero_item),
    CONSTRAINT uq_item_version_id UNIQUE(id_version_instrumento, id_item),
    CONSTRAINT chk_item_num CHECK(numero_item > 0)
);

CREATE TABLE dbo.instrumento_opciones_respuesta (
    id_version_instrumento BIGINT NOT NULL,
    valor SMALLINT NOT NULL,
    etiqueta VARCHAR(250) NOT NULL,
    PRIMARY KEY(id_version_instrumento, valor),
    CONSTRAINT fk_opcion_version FOREIGN KEY(id_version_instrumento) REFERENCES dbo.instrumento_versiones(id_version_instrumento) DEFERRABLE INITIALLY IMMEDIATE,
