BEGIN;

-- ----------------------------------------------------------------------------
-- 1. CATÁLOGOS Y PROCEDENCIA DE DATOS (RQ-BI-01, RQ-BI-02, RQ-BI-03, RQ-BI-04)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS fuentes_datos (
    id_fuente           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_fuente       VARCHAR(40)  NOT NULL,
    nombre_fuente       VARCHAR(150) NOT NULL,
    naturaleza_dato     VARCHAR(12)  NOT NULL,
    tipo_fuente         VARCHAR(35)  NOT NULL,
    periodo_referencia  VARCHAR(30)  NOT NULL,
    ambito_geografico   VARCHAR(100) NULL,
    referencia_origen   VARCHAR(250) NULL,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_fuentes_codigo UNIQUE (codigo_fuente),
    CONSTRAINT uq_fuentes_id_naturaleza UNIQUE (id_fuente, naturaleza_dato),
    CONSTRAINT chk_fuentes_naturaleza CHECK (naturaleza_dato IN ('REAL', 'SINTETICO')),
    CONSTRAINT chk_fuentes_tipo CHECK (
        tipo_fuente IN ('CASO_UNIVERSITARIO_SIMULADO', 'REPOSITORIO_ACADEMICO_REAL', 'CANDIDATA_EXTERNA')
    )
);

CREATE TABLE IF NOT EXISTS cat_practicas (
    id_practica         SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_practica     VARCHAR(30)  NOT NULL,
    nombre_practica     VARCHAR(100) NOT NULL,
    es_mixto            BOOLEAN      NOT NULL DEFAULT FALSE,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_cat_practicas_codigo UNIQUE (codigo_practica)
);

CREATE TABLE IF NOT EXISTS cat_instrumentos (
    id_instrumento          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_instrumento      VARCHAR(15)  NOT NULL,
    version_instrumento     VARCHAR(30)  NOT NULL,
    nombre_instrumento      VARCHAR(120) NOT NULL,
    puntaje_minimo          SMALLINT     NOT NULL,
    puntaje_maximo          SMALLINT     NOT NULL,
    requiere_evento_indice  BOOLEAN      NOT NULL,
    activo                  BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_cat_instr_codigo_ver UNIQUE (codigo_instrumento, version_instrumento),
    CONSTRAINT uq_cat_instr_id_codigo UNIQUE (id_instrumento, codigo_instrumento),
    CONSTRAINT chk_cat_instr_codigo CHECK (codigo_instrumento IN ('PSS-10', 'PCL-5')),
    CONSTRAINT chk_cat_instr_rango CHECK (
        (codigo_instrumento = 'PSS-10' AND puntaje_minimo = 0 AND puntaje_maximo = 40 AND requiere_evento_indice = FALSE)
        OR
        (codigo_instrumento = 'PCL-5'  AND puntaje_minimo = 0 AND puntaje_maximo = 80 AND requiere_evento_indice = TRUE)
    )
);

CREATE TABLE IF NOT EXISTS cat_categorias_evento_indice (
    id_categoria_evento SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_categoria    VARCHAR(40)  NOT NULL,
    nombre_categoria    VARCHAR(120) NOT NULL,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_cat_evento_codigo UNIQUE (codigo_categoria)
);

-- ----------------------------------------------------------------------------
-- 2. ESTUDIANTES, PROGRAMAS, SESIONES, ASIGNACIONES Y ASISTENCIAS
--    (RQ-BI-06, RQ-BI-07, E-1, E-2, RO-03, KPI-03, RG-03)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS estudiantes (
    id_estudiante       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente           BIGINT       NOT NULL,
    naturaleza_dato     VARCHAR(12)  NOT NULL,
    codigo_anonimizado  VARCHAR(50)  NOT NULL,
    edad_anios          SMALLINT     NULL,
    grupo_etario        VARCHAR(20)  NULL,
    sexo_codificado     VARCHAR(20)  NULL,
    facultad_o_area     VARCHAR(80)  NULL,
    ciclo_academico     SMALLINT     NULL,
    creado_en           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_est_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT uq_est_fuente_codigo UNIQUE (id_fuente, codigo_anonimizado),
    CONSTRAINT uq_est_fuente_id UNIQUE (id_fuente, id_estudiante),
    CONSTRAINT chk_est_edad_adulto CHECK (edad_anios IS NULL OR (edad_anios BETWEEN 18 AND 99)),
    CONSTRAINT chk_est_ciclo CHECK (ciclo_academico IS NULL OR (ciclo_academico BETWEEN 1 AND 14))
);

CREATE TABLE IF NOT EXISTS programas (
    id_programa             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente               BIGINT       NOT NULL,
    naturaleza_dato         VARCHAR(12)  NOT NULL,
    codigo_programa         VARCHAR(40)  NOT NULL,
    nombre_programa         VARCHAR(150) NOT NULL,
    periodo_academico       VARCHAR(20)  NOT NULL,
    id_practica_principal   SMALLINT     NOT NULL,
    fecha_inicio            DATE         NOT NULL,
    fecha_cierre            DATE         NOT NULL,
    dias_ventana_inicial    SMALLINT     NOT NULL DEFAULT 14,
    dias_ventana_final      SMALLINT     NOT NULL DEFAULT 14,
    ventana_inicial_inicio  DATE         NOT NULL,
    ventana_inicial_fin     DATE         NOT NULL,
    ventana_final_inicio    DATE         NOT NULL,
    ventana_final_fin       DATE         NOT NULL,
    estado_programa         VARCHAR(20)  NOT NULL DEFAULT 'PLANIFICADO',
    creado_en               TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_prog_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_prog_practica
        FOREIGN KEY (id_practica_principal)
        REFERENCES cat_practicas (id_practica),
    CONSTRAINT uq_prog_fuente_codigo UNIQUE (id_fuente, codigo_programa),
    CONSTRAINT uq_prog_fuente_id UNIQUE (id_fuente, id_programa),
    CONSTRAINT chk_prog_fechas CHECK (fecha_cierre >= fecha_inicio),
    CONSTRAINT chk_prog_dias_ventana CHECK (dias_ventana_inicial >= 0 AND dias_ventana_final >= 0),
    CONSTRAINT chk_prog_ventanas CHECK (
        ventana_inicial_inicio <= ventana_inicial_fin
        AND ventana_final_inicio <= ventana_final_fin
        AND ventana_final_inicio >= ventana_inicial_fin
    ),
    CONSTRAINT chk_prog_estado CHECK (
        estado_programa IN ('PLANIFICADO', 'ACTIVO', 'FINALIZADO', 'CANCELADO')
    )
);

CREATE TABLE IF NOT EXISTS sesiones (
    id_sesion               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente               BIGINT       NOT NULL,
    naturaleza_dato         VARCHAR(12)  NOT NULL,
    id_programa             BIGINT       NOT NULL,
    numero_sesion           SMALLINT     NOT NULL,
    id_practica_tecnica     SMALLINT     NOT NULL,
    modalidad               VARCHAR(15)  NOT NULL,
    duracion_programada_min SMALLINT     NOT NULL,
    fecha_sesion            DATE         NOT NULL,
    fecha_hora_inicio       TIMESTAMPTZ  NOT NULL,
    estado_sesion           VARCHAR(20)  NOT NULL DEFAULT 'PROGRAMADA',
    fecha_cambio_estado     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_estado_codigo    VARCHAR(40)  NULL,

    CONSTRAINT fk_ses_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_ses_programa
        FOREIGN KEY (id_fuente, id_programa)
        REFERENCES programas (id_fuente, id_programa),
    CONSTRAINT fk_ses_practica
        FOREIGN KEY (id_practica_tecnica)
        REFERENCES cat_practicas (id_practica),
    CONSTRAINT uq_ses_prog_numero UNIQUE (id_programa, numero_sesion),
    CONSTRAINT uq_ses_fuente_prog_id UNIQUE (id_fuente, id_programa, id_sesion),
    CONSTRAINT chk_ses_numero CHECK (numero_sesion > 0),
    CONSTRAINT chk_ses_modalidad CHECK (modalidad IN ('PRESENCIAL', 'VIRTUAL', 'HIBRIDA')),
    CONSTRAINT chk_ses_duracion CHECK (duracion_programada_min BETWEEN 5 AND 480),
    CONSTRAINT chk_ses_estado CHECK (
        estado_sesion IN ('PROGRAMADA', 'REALIZADA', 'CANCELADA', 'NO_REALIZADA')
    )
);

CREATE TABLE IF NOT EXISTS asignaciones (
    id_asignacion         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente             BIGINT       NOT NULL,
    naturaleza_dato       VARCHAR(12)  NOT NULL,
    id_estudiante         BIGINT       NOT NULL,
    id_programa           BIGINT       NOT NULL,
    fecha_inscripcion     DATE         NOT NULL,
    estado_asignacion     VARCHAR(20)  NOT NULL DEFAULT 'INSCRITO',
    fecha_retiro          DATE         NULL,
    motivo_retiro_codigo  VARCHAR(40)  NULL,
    actualizado_en        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_asig_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_asig_estudiante
        FOREIGN KEY (id_fuente, id_estudiante)
        REFERENCES estudiantes (id_fuente, id_estudiante),
    CONSTRAINT fk_asig_programa
        FOREIGN KEY (id_fuente, id_programa)
        REFERENCES programas (id_fuente, id_programa),
    CONSTRAINT uq_asig_est_prog UNIQUE (id_estudiante, id_programa),
    CONSTRAINT uq_asig_fuente_prog_id UNIQUE (id_fuente, id_programa, id_asignacion),
    CONSTRAINT uq_asig_compuesta UNIQUE (id_fuente, id_estudiante, id_programa, id_asignacion),
    CONSTRAINT chk_asig_estado CHECK (
        estado_asignacion IN ('INSCRITO', 'ACTIVO', 'RETIRADO', 'COMPLETADO')
    ),
    CONSTRAINT chk_asig_retiro_coherente CHECK (
        (estado_asignacion = 'RETIRADO' AND fecha_retiro IS NOT NULL AND fecha_retiro >= fecha_inscripcion)
        OR
        (estado_asignacion <> 'RETIRADO' AND fecha_retiro IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS asistencias (
    id_asistencia       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente           BIGINT       NOT NULL,
    naturaleza_dato     VARCHAR(12)  NOT NULL,
    id_programa         BIGINT       NOT NULL,
    id_asignacion       BIGINT       NOT NULL,
    id_sesion           BIGINT       NOT NULL,
    estado_asistencia   VARCHAR(20)  NOT NULL,
    minutos_asistidos   SMALLINT     NULL,
    registrado_en       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_asis_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_asis_asignacion
        FOREIGN KEY (id_fuente, id_programa, id_asignacion)
        REFERENCES asignaciones (id_fuente, id_programa, id_asignacion),
    CONSTRAINT fk_asis_sesion
        FOREIGN KEY (id_fuente, id_programa, id_sesion)
        REFERENCES sesiones (id_fuente, id_programa, id_sesion),
    CONSTRAINT uq_asis_asig_sesion UNIQUE (id_asignacion, id_sesion),
    CONSTRAINT chk_asis_estado CHECK (
        estado_asistencia IN ('ASISTIO', 'INASISTENCIA', 'RETIRO_BAJA')
    ),
    CONSTRAINT chk_asis_minutos CHECK (
        minutos_asistidos IS NULL
        OR (estado_asistencia = 'ASISTIO' AND minutos_asistidos > 0 AND minutos_asistidos <= 480)
        OR (estado_asistencia <> 'ASISTIO' AND minutos_asistidos = 0)
    )
);

-- ----------------------------------------------------------------------------
-- 3. EVENTOS ÍNDICE Y EVALUACIONES PSICOLÓGICAS (PSS-10 / PCL-5)
--    (RQ-BI-03, RQ-BI-04, RQ-BI-05, KPI-01, KPI-02, KPI-04, RO-04, RG-01)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS eventos_indice (
    id_evento_indice      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente             BIGINT       NOT NULL,
    naturaleza_dato       VARCHAR(12)  NOT NULL,
    id_estudiante         BIGINT       NOT NULL,
    id_categoria_evento   SMALLINT     NOT NULL,
    codigo_evento_local   VARCHAR(30)  NOT NULL,
    anio_ocurrencia_aprox SMALLINT     NULL,
    vigente               BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_evt_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_evt_estudiante
        FOREIGN KEY (id_fuente, id_estudiante)
        REFERENCES estudiantes (id_fuente, id_estudiante),
    CONSTRAINT fk_evt_categoria
        FOREIGN KEY (id_categoria_evento)
        REFERENCES cat_categorias_evento_indice (id_categoria_evento),
    CONSTRAINT uq_evt_est_codigo UNIQUE (id_estudiante, codigo_evento_local),
    CONSTRAINT uq_evt_fuente_est_id UNIQUE (id_fuente, id_estudiante, id_evento_indice),
    CONSTRAINT chk_evt_anio CHECK (
        anio_ocurrencia_aprox IS NULL OR (anio_ocurrencia_aprox BETWEEN 1950 AND 2030)
    )
);

CREATE TABLE IF NOT EXISTS oportunidades_evaluacion (
    id_oportunidad       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente            BIGINT       NOT NULL,
    naturaleza_dato      VARCHAR(12)  NOT NULL,
    id_asignacion        BIGINT       NOT NULL,
    id_estudiante        BIGINT       NOT NULL,
    id_programa          BIGINT       NOT NULL,
    id_instrumento       SMALLINT     NOT NULL,
    codigo_instrumento   VARCHAR(15)  NOT NULL,
    id_evento_indice     BIGINT       NULL,
    momento              VARCHAR(10)  NOT NULL,
    fecha_ventana_inicio DATE         NOT NULL,
    fecha_ventana_fin    DATE         NOT NULL,
    fecha_prevista       DATE         NOT NULL,
    aplicable            BOOLEAN      NOT NULL DEFAULT TRUE,
    motivo_no_aplicable  VARCHAR(60)  NULL,
    creado_en            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_op_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_op_asignacion
        FOREIGN KEY (id_fuente, id_estudiante, id_programa, id_asignacion)
        REFERENCES asignaciones (id_fuente, id_estudiante, id_programa, id_asignacion),
    CONSTRAINT fk_op_instrumento
        FOREIGN KEY (id_instrumento, codigo_instrumento)
        REFERENCES cat_instrumentos (id_instrumento, codigo_instrumento),
    CONSTRAINT fk_op_evento_indice
        FOREIGN KEY (id_fuente, id_estudiante, id_evento_indice)
        REFERENCES eventos_indice (id_fuente, id_estudiante, id_evento_indice),
    CONSTRAINT uq_op_fuente_id_instr UNIQUE (id_fuente, id_oportunidad, codigo_instrumento),
    CONSTRAINT chk_op_momento CHECK (momento IN ('INICIAL', 'FINAL')),
    CONSTRAINT chk_op_fechas CHECK (
        fecha_ventana_inicio <= fecha_ventana_fin
        AND fecha_prevista BETWEEN fecha_ventana_inicio AND fecha_ventana_fin
    ),
    CONSTRAINT chk_op_aplicabilidad CHECK (
        (aplicable = TRUE  AND motivo_no_aplicable IS NULL)
        OR
        (aplicable = FALSE AND motivo_no_aplicable IS NOT NULL)
    ),
    CONSTRAINT chk_op_evento_segun_instrumento CHECK (
        (codigo_instrumento = 'PSS-10' AND id_evento_indice IS NULL)
        OR
        (codigo_instrumento = 'PCL-5'  AND (aplicable = FALSE OR id_evento_indice IS NOT NULL))
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_op_pss10_unica
    ON oportunidades_evaluacion (id_asignacion, id_instrumento, momento)
    WHERE codigo_instrumento = 'PSS-10';

CREATE UNIQUE INDEX IF NOT EXISTS uq_op_pcl5_unica_con_evento
    ON oportunidades_evaluacion (id_asignacion, id_instrumento, momento, id_evento_indice)
    WHERE codigo_instrumento = 'PCL-5' AND id_evento_indice IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_op_pcl5_no_aplicable_unica
    ON oportunidades_evaluacion (id_asignacion, id_instrumento, momento)
    WHERE codigo_instrumento = 'PCL-5' AND id_evento_indice IS NULL;

CREATE TABLE IF NOT EXISTS resultados_evaluacion (
    id_resultado             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente                BIGINT       NOT NULL,
    naturaleza_dato          VARCHAR(12)  NOT NULL,
    id_oportunidad           BIGINT       NOT NULL,
    codigo_instrumento       VARCHAR(15)  NOT NULL,
    numero_version           SMALLINT     NOT NULL DEFAULT 1,
    puntaje_total            SMALLINT     NOT NULL,
    fecha_realizacion        DATE         NOT NULL,
    en_ventana               BOOLEAN      NOT NULL,
    estado_validez           VARCHAR(15)  NOT NULL DEFAULT 'VALIDO',
    es_vigente               BOOLEAN      NOT NULL DEFAULT TRUE,
    id_resultado_reemplazado BIGINT       NULL,
    motivo_correccion        VARCHAR(150) NULL,
    vigente_desde            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vigente_hasta            TIMESTAMPTZ  NULL,

    CONSTRAINT fk_res_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_res_oportunidad
        FOREIGN KEY (id_fuente, id_oportunidad, codigo_instrumento)
        REFERENCES oportunidades_evaluacion (id_fuente, id_oportunidad, codigo_instrumento),
    CONSTRAINT fk_res_reemplazado
        FOREIGN KEY (id_resultado_reemplazado)
        REFERENCES resultados_evaluacion (id_resultado),
    CONSTRAINT uq_res_op_version UNIQUE (id_oportunidad, numero_version),
    CONSTRAINT chk_res_version CHECK (numero_version >= 1),
    CONSTRAINT chk_res_puntaje_rango CHECK (
        (codigo_instrumento = 'PSS-10' AND puntaje_total BETWEEN 0 AND 40)
        OR
        (codigo_instrumento = 'PCL-5'  AND puntaje_total BETWEEN 0 AND 80)
    ),
    CONSTRAINT chk_res_estado CHECK (estado_validez IN ('VALIDO', 'REEMPLAZADO', 'ANULADO')),
    CONSTRAINT chk_res_vigencia_coherente CHECK (
        (es_vigente = TRUE  AND estado_validez = 'VALIDO' AND vigente_hasta IS NULL)
        OR
        (es_vigente = FALSE AND estado_validez IN ('REEMPLAZADO', 'ANULADO') AND vigente_hasta IS NOT NULL)
    ),
    CONSTRAINT chk_res_correccion CHECK (
        (numero_version = 1 AND id_resultado_reemplazado IS NULL)
        OR
        (numero_version > 1 AND id_resultado_reemplazado IS NOT NULL AND motivo_correccion IS NOT NULL)
    ),
    CONSTRAINT chk_res_fechas_vigencia CHECK (
        vigente_hasta IS NULL OR vigente_hasta >= vigente_desde
    )
);

-- Como máximo un resultado válido vigente por oportunidad
CREATE UNIQUE INDEX IF NOT EXISTS uq_resultado_vigente_por_oportunidad
    ON resultados_evaluacion (id_oportunidad)
    WHERE es_vigente = TRUE AND estado_validez = 'VALIDO';

-- ----------------------------------------------------------------------------
-- 4. AUDITORÍA OPERATIVA (HISTORIAL DE ESTADOS)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS historial_estados_sesion (
    id_historial_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion           BIGINT       NOT NULL REFERENCES sesiones (id_sesion),
    estado_anterior     VARCHAR(20)  NULL,
    estado_nuevo        VARCHAR(20)  NOT NULL,
    fecha_cambio        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_codigo       VARCHAR(40)  NULL,

    CONSTRAINT chk_hses_estado CHECK (
        estado_nuevo IN ('PROGRAMADA', 'REALIZADA', 'CANCELADA', 'NO_REALIZADA')
    )
);

CREATE TABLE IF NOT EXISTS historial_estados_asignacion (
    id_historial_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion           BIGINT       NOT NULL REFERENCES asignaciones (id_asignacion),
    estado_anterior         VARCHAR(20)  NULL,
    estado_nuevo            VARCHAR(20)  NOT NULL,
    fecha_efectiva          DATE         NOT NULL,
    fecha_registro          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_codigo           VARCHAR(40)  NULL,

    CONSTRAINT chk_hasig_estado CHECK (
        estado_nuevo IN ('INSCRITO', 'ACTIVO', 'RETIRADO', 'COMPLETADO')
    )
);

-- ----------------------------------------------------------------------------
-- 5. VARIABLES COMPLEMENTARIAS OPCIONALES (RQ-BI-12, AISLADAS DEL NÚCLEO)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS cat_variables_complementarias (
    id_variable        SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_variable    VARCHAR(35)   NOT NULL,
    nombre_variable    VARCHAR(100)  NOT NULL,
    unidad_medida      VARCHAR(30)   NOT NULL,
    metodo_medicion    VARCHAR(80)   NOT NULL,
    valor_minimo       NUMERIC(10,3) NULL,
    valor_maximo       NUMERIC(10,3) NULL,
    activo             BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_cat_var_comp_codigo UNIQUE (codigo_variable)
);

CREATE TABLE IF NOT EXISTS mediciones_complementarias (
    id_medicion         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente           BIGINT        NOT NULL,
    naturaleza_dato     VARCHAR(12)   NOT NULL,
    id_estudiante       BIGINT        NOT NULL,
    id_asignacion       BIGINT        NULL,
    id_variable         SMALLINT      NOT NULL,
    valor_numerico      NUMERIC(10,3) NOT NULL,
    unidad_medida       VARCHAR(30)   NOT NULL,
    metodo_medicion     VARCHAR(80)   NOT NULL,
    fecha_hora_medicion TIMESTAMPTZ   NOT NULL,
    es_vigente          BOOLEAN       NOT NULL DEFAULT TRUE,
    registrado_en       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mcomp_fuente
        FOREIGN KEY (id_fuente, naturaleza_dato)
        REFERENCES fuentes_datos (id_fuente, naturaleza_dato),
    CONSTRAINT fk_mcomp_estudiante
        FOREIGN KEY (id_fuente, id_estudiante)
        REFERENCES estudiantes (id_fuente, id_estudiante),
    CONSTRAINT fk_mcomp_asignacion
        FOREIGN KEY (id_asignacion)
        REFERENCES asignaciones (id_asignacion),
    CONSTRAINT fk_mcomp_variable
        FOREIGN KEY (id_variable)
        REFERENCES cat_variables_complementarias (id_variable)
);

-- ----------------------------------------------------------------------------
-- 6. REGLAS OPERATIVAS ENTRE TABLAS (TRIGGERS DE INTEGRIDAD)
-- ----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_validar_asistencia_sesion()
RETURNS TRIGGER AS $$
DECLARE
    v_estado_sesion VARCHAR(20);
BEGIN
    SELECT estado_sesion
      INTO v_estado_sesion
      FROM sesiones
     WHERE id_sesion = NEW.id_sesion;

    IF v_estado_sesion <> 'REALIZADA' AND NEW.estado_asistencia IN ('ASISTIO', 'INASISTENCIA') THEN
        RAISE EXCEPTION
            'No se puede registrar % sobre la sesión % con estado %. Las sesiones canceladas, no realizadas o programadas no generan asistencias ni inasistencias.',
            NEW.estado_asistencia, NEW.id_sesion, v_estado_sesion;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validar_asistencia_sesion ON asistencias;
CREATE TRIGGER trg_validar_asistencia_sesion
    BEFORE INSERT OR UPDATE ON asistencias
    FOR EACH ROW
    EXECUTE FUNCTION fn_validar_asistencia_sesion();

CREATE OR REPLACE FUNCTION fn_validar_resultado_oportunidad()
RETURNS TRIGGER AS $$
DECLARE
    v_aplicable      BOOLEAN;
    v_inicio_ventana DATE;
    v_fin_ventana    DATE;
    v_en_ventana     BOOLEAN;
BEGIN
    SELECT aplicable, fecha_ventana_inicio, fecha_ventana_fin
      INTO v_aplicable, v_inicio_ventana, v_fin_ventana
      FROM oportunidades_evaluacion
     WHERE id_oportunidad = NEW.id_oportunidad;

    IF NOT v_aplicable THEN
        RAISE EXCEPTION
            'No se puede registrar un resultado para la oportunidad % porque está marcada como no aplicable.',
            NEW.id_oportunidad;
    END IF;

    v_en_ventana := (NEW.fecha_realizacion BETWEEN v_inicio_ventana AND v_fin_ventana);
    IF NEW.en_ventana IS DISTINCT FROM v_en_ventana THEN
        RAISE EXCEPTION
            'Inconsistencia en en_ventana para oportunidad %: fecha_realizacion (%) vs ventana [% .. %].',
            NEW.id_oportunidad, NEW.fecha_realizacion, v_inicio_ventana, v_fin_ventana;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validar_resultado_oportunidad ON resultados_evaluacion;
CREATE TRIGGER trg_validar_resultado_oportunidad
    BEFORE INSERT OR UPDATE ON resultados_evaluacion
    FOR EACH ROW
    EXECUTE FUNCTION fn_validar_resultado_oportunidad();

